/**
 * Weight-room library. No on-court volleyball drills on purpose: this app covers
 * lifting, power work and prehab that support practice.
 *
 * equipment: each inner list is one way to set the exercise up; the exercise fits a
 * gym when ANY one of those lists is fully available. [] means no equipment needed.
 * Ids from 1.0 are kept so older programs and workout logs still resolve.
 */

type Opts = { easier?: string; harder?: string };

function x(
  id: string,
  name: string,
  category: ExerciseCategory,
  pattern: Pattern,
  weighted: boolean,
  level: 1 | 2 | 3,
  equipment: Equipment[][],
  cue: string,
  howTo: HowTo,
  opts: Opts = {},
): Exercise {
  const tier = TIER_IDS[id] ?? (category === 'power' ? 'P' : category === 'prehab' ? 'D' : category === 'core' ? 'C' : 'B');
  return { id, name, category, pattern, weighted, level, equipment, cue, howTo, tier, ...opts };
}

