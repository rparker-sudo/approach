function x(
  id: string,
  name: string,
  category: ExerciseCategory,
  pattern: Pattern,
  weighted: boolean,
  level: 1 | 2 | 3,
  equipment: Equipment[][],
  cue: string,
  howTo: HowTo,
  opts: Opts = {},
): Exercise {
  const cardio = category === 'cardio';
  return {
    id,
    name,
    category,
    pattern,
    weighted,
    level,
    equipment,
    cue,
    howTo,
    tier: TIER[id],
    scope: cardio ? 'general' : 'all',
    ...(cardio ? { durationOnly: true } : {}),
    ...opts,
  };
}

